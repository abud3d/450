<?php
declare(strict_types=1);
require __DIR__.'/../app/Game/Seating.php';
require __DIR__.'/../app/Game/Projects.php';
require __DIR__.'/../app/Game/Scoring.php';
require __DIR__.'/../app/Game/Rules.php';
use Baloot\Game\Rules;
use Baloot\Game\Seating;
use Baloot\Game\Projects;
use Baloot\Game\Scoring;
function check(bool $ok,string $message):void{if(!$ok)throw new RuntimeException($message);}
check(Seating::counterClockwiseSeat(0)===3,'seat order');
check(count(Rules::deck())===32,'32-card deck');
$g=Rules::create();Rules::deal($g);
check($g['phase']==='auction1','deal phase');
check(array_sum(array_map('count',$g['hands']))===20,'initial 5-card deal');
check(count($g['stock'])===11,'remaining stock');
$hand=[['suit'=>'S','rank'=>'A','id'=>'SA'],['suit'=>'S','rank'=>'K','id'=>'SK'],['suit'=>'S','rank'=>'Q','id'=>'SQ'],['suit'=>'H','rank'=>'7','id'=>'H7']];
$projects=Projects::detect($hand,['type'=>'hokum','trump'=>'S'],0);
check(count(array_filter($projects,fn($p)=>$p['type']==='20'))===1,'three-card run detection');
check(count(array_filter($projects,fn($p)=>$p['type']==='belot'))===1,'belot detection');
check(Rules::points(['suit'=>'S','rank'=>'J'],['type'=>'hokum','trump'=>'S'])===20,'trump jack points');
check(Rules::points(['suit'=>'H','rank'=>'A'],['type'=>'hokum','trump'=>'S'])===11,'off-trump ace points');
check(Scoring::convertRaw(65,'sun')===13,'sun conversion');
check(Scoring::convertRaw(81,'hokum')===8,'hokum conversion');
$hokum=['type'=>'hokum','trump'=>'S'];
$leadTrump=[['seat'=>0,'card'=>['suit'=>'S','rank'=>'8','id'=>'S8']]];
$overHand=[['suit'=>'S','rank'=>'8','id'=>'S8'],['suit'=>'S','rank'=>'9','id'=>'S9'],['suit'=>'H','rank'=>'7','id'=>'H7']];
$over=Rules::legal($overHand,$leadTrump,$hokum,1);
check(array_column($over,'id')===['S9'],'must overtrump a trump lead when a higher trump is available');
$partnerTrump=[['seat'=>2,'card'=>['suit'=>'S','rank'=>'8','id'=>'S8']]];
$partnerHand=[['suit'=>'S','rank'=>'8','id'=>'S8'],['suit'=>'S','rank'=>'9','id'=>'S9']];
check(count(Rules::legal($partnerHand,$partnerTrump,$hokum,0))===2,'do not require overtrumping a partner highest trump');
$offSuit=[['seat'=>0,'card'=>['suit'=>'H','rank'=>'7','id'=>'H7']]];
$cutHand=[['suit'=>'S','rank'=>'9','id'=>'S9'],['suit'=>'D','rank'=>'7','id'=>'D7']];
$cut=Rules::legal($cutHand,$offSuit,$hokum,1);
check(array_column($cut,'id')===['S9'],'must trump when void in the led suit and holding trump');
$trumpAlready=[['seat'=>0,'card'=>['suit'=>'H','rank'=>'7','id'=>'H7']],['seat'=>3,'card'=>['suit'=>'S','rank'=>'9','id'=>'S9']]];
$overcutHand=[['suit'=>'S','rank'=>'8','id'=>'S8'],['suit'=>'S','rank'=>'J','id'=>'SJ'],['suit'=>'D','rank'=>'7','id'=>'D7']];
$overcut=Rules::legal($overcutHand,$trumpAlready,$hokum,2);
check(array_column($overcut,'id')===['SJ'],'must overtrump an opponent trump when a higher trump is available');
$noTrumpHand=[['suit'=>'D','rank'=>'7','id'=>'D7'],['suit'=>'C','rank'=>'8','id'=>'C8']];
check(count(Rules::legal($noTrumpHand,$offSuit,$hokum,1))===2,'when void in the led suit and holding no trump, any card is allowed');
$qaidHokum=['phase'=>'playing','turn'=>1,'qaidEnabled'=>true,'contract'=>$hokum,'hands'=>[[],[['suit'=>'S','rank'=>'9','id'=>'S9'],['suit'=>'D','rank'=>'8','id'=>'D8']],[],[]],'trick'=>$offSuit,'history'=>[],'tricks'=>[],'balotClaims'=>[],'lastWinner'=>null,'doubleWindow'=>false];
Rules::play($qaidHokum,1,'D8');
$proof=$qaidHokum['history'][0]??[];
check(!empty($proof['violation'])&&($proof['proofCard']['id']??'')==='S9','qaid must record proof when a player fails to trump despite holding trump');
$qaidNoTrump=['phase'=>'playing','turn'=>1,'qaidEnabled'=>true,'contract'=>$hokum,'hands'=>[[],[['suit'=>'D','rank'=>'7','id'=>'D7'],['suit'=>'C','rank'=>'8','id'=>'C8']],[],[]],'trick'=>$offSuit,'history'=>[],'tricks'=>[],'balotClaims'=>[],'lastWinner'=>null,'doubleWindow'=>false];
Rules::play($qaidNoTrump,1,'C8');
$proof=$qaidNoTrump['history'][0]??[];
check(empty($proof['violation'])&&empty($proof['proofCard']),'discarding without a trump in hand is legal and must not trigger qaid');
$qaidOvertrump=['phase'=>'playing','turn'=>2,'qaidEnabled'=>true,'contract'=>$hokum,'hands'=>[[],[],[['suit'=>'S','rank'=>'8','id'=>'S8'],['suit'=>'S','rank'=>'J','id'=>'SJ']],[]],'trick'=>$trumpAlready,'history'=>[],'tricks'=>[],'balotClaims'=>[],'lastWinner'=>null,'doubleWindow'=>false];
Rules::play($qaidOvertrump,2,'S8');
$proof=$qaidOvertrump['history'][0]??[];
check(!empty($proof['violation'])&&($proof['proofCard']['id']??'')==='SJ','qaid must record the higher trump proving an undertrump');
echo "PHP game engine smoke tests passed\n";
