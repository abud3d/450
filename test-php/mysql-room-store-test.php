use Baloot\Game\Engine;
use Baloot\Infrastructure\RoomStore;
function verify(bool $condition,string $message):void{if(!$condition)throw new RuntimeException($message);}
$store=new RoomStore();
$quickOwner=str_repeat('d',64);$quickGuest=str_repeat('e',64);
$waiting=$store->create($quickOwner,'Waiting Room',true);
$quick=$store->quickJoin($quickGuest,'Quick Guest',true);
verify($quick['code']===$waiting['code'] && $quick['seat']===1 && $quick['created']===false,'quick join selects a compatible lobby');
$solo=$store->quickJoin(str_repeat('f',64),'Solo Guest',false);
verify($solo['created']===true && $solo['qaidEnabled']===false,'quick join creates a room when no compatible lobby exists');
$owner=str_repeat('a',64);$guest=str_repeat('b',64);
$created=$store->create($owner,'Host',true);$code=$created['code'];
verify(strlen($code)===6,'room code format');
$joined=$store->join($code,$guest,'Guest');
verify($joined['seat']===1,'guest joins first free seat');
$moveId='11111111-1111-4111-8111-111111111111';
$moved=$store->moveSeat($code,$guest,3,$moveId);
verify($moved['seat']===3,'player moves to free seat');
$afterMove=$store->read($code);
verify(($afterMove['state']['players'][3]['guestId']??'')===$guest,'seat movement persists');
$version=(int)$afterMove['version'];
$actionId='22222222-2222-4222-8222-222222222222';
$first=$store->mutate($code,$owner,$actionId,'test_change',function(array &$state,int $seat):array{$state['testMarker']='once';return ['value'=>42];},$version);
$duplicate=$store->mutate($code,$owner,$actionId,'test_change',function(array &$state,int $seat):array{throw new RuntimeException('duplicate action was executed twice');});
verify($first===$duplicate && $duplicate['value']===42,'action idempotency');
$afterAction=$store->read($code);
verify(($afterAction['state']['testMarker']??'')==='once' && $afterAction['version']===$version+1,'single version increment');
verify($store->allowRate('test',str_repeat('c',64),2,60),'rate limit first hit');
verify($store->allowRate('test',str_repeat('c',64),2,60),'rate limit second hit');
verify(!$store->allowRate('test',str_repeat('c',64),2,60),'rate limit blocks excess hit');
$startId='33333333-3333-4333-8333-333333333333';
$store->mutate($code,$owner,$startId,'start',function(array &$state,int $seat):array{Engine::start($state,$seat);return ['ok'=>true];});
$started=$store->read($code);
verify(($started['state']['game']['phase']??'')==='auction1','game state persisted in MySQL');
$deadlineId='44444444-4444-4444-8444-444444444444';
$store->mutate($code,$owner,$deadlineId,'test_deadline',function(array &$state,int $seat):array{$state['game']['turn']=0;$state['turnDeadlineAt']=time()-1;return ['ok'=>true];});
verify($store->advanceDueRooms(20)>=1,'cron advances an expired room');
$timed=$store->read($code);
verify(($timed['state']['timeoutSeat']??-1)===0,'expired human turn is prompted');
$graceId='55555555-5555-4555-8555-555555555555';
$store->mutate($code,$owner,$graceId,'test_grace',function(array &$state,int $seat):array{$state['timeoutGraceUntil']=time()-1;$state['turnDeadlineAt']=time()-1;return ['ok'=>true];});
$store->advanceDueRooms(20);
$recovered=$store->read($code);
verify(!empty($recovered['state']['players'][0]['botControl']),'bot takes over after timeout grace');
echo "MySQL room store, idempotency, rate limit and cron recovery tests passed\n";
