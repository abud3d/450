<?php
declare(strict_types=1);
require_once __DIR__ . '/../app/Game/Seating.php';
require_once __DIR__ . '/../app/Game/Projects.php';
require_once __DIR__ . '/../app/Game/Scoring.php';
require_once __DIR__ . '/../app/Game/Rules.php';
require_once __DIR__ . '/../app/Game/Purchase.php';
require_once __DIR__ . '/../app/Game/Bot.php';
require_once __DIR__ . '/../app/Game/TurnClock.php';
require_once __DIR__ . '/../app/Game/Qaid.php';
require_once __DIR__ . '/../app/Game/Engine.php';
require_once __DIR__ . '/../app/Infrastructure/Database.php';
require_once __DIR__ . '/../app/Infrastructure/RoomStore.php';
use Baloot\Game\Engine;
use Baloot\Game\Rules;
use Baloot\Infrastructure\RoomStore;
use Baloot\Infrastructure\Database;
function verify(bool $condition,string $message):void{if(!$condition)throw new RuntimeException($message);}
$store=new RoomStore();
$quickOwner=str_repeat('d',64);$quickGuest=str_repeat('e',64);
$waiting=$store->create($quickOwner,'Waiting Room',true);
$quick=$store->quickJoin($quickGuest,'Quick Guest',true);
verify($quick['code']===$waiting['code'] && $quick['seat']===1 && $quick['created']===false,'quick join selects a compatible lobby');
$solo=$store->quickJoin(str_repeat('f',64),'Solo Guest',false);
verify($solo['created']===true && $solo['qaidEnabled']===false,'quick join creates a room when no compatible lobby exists');
$owner=str_repeat('a',64);$guest=str_repeat('b',64);
$created=$store->create($owner,'Host',true);$code=$created['code'];
verify((bool)preg_match('/^[0-9]{4}$/',$code),'room code is four numeric digits');
$joined=$store->join($code,$guest,'Guest');
verify($joined['seat']===1,'guest joins first free seat');
$moveId='11111111-1111-4111-8111-111111111111';
$moved=$store->moveSeat($code,$guest,3,$moveId);
verify($moved['seat']===3,'player moves to free seat');
$afterMove=$store->read($code);
verify(($afterMove['state']['players'][3]['guestId']??'')===$guest,'seat movement persists');
$guest2=str_repeat('c',64);$guest3=str_repeat('d',64);
$joined2=$store->join($code,$guest2,'Guest Two');
$joined3=$store->join($code,$guest3,'Guest Three');
verify($joined2['seat']===1 && $joined3['seat']===2,'four distinct human players occupy all four seats');
$pdo=Database::connection();
$staleOwner=str_repeat('9',64);
$staleRoom=$store->create($staleOwner,'Stale Lobby',true);
$age=$pdo->prepare('UPDATE baloot_rooms SET last_activity_at=UTC_TIMESTAMP(6)-INTERVAL 10 MINUTE WHERE room_code=?');
$age->execute([$staleRoom['code']]);
$staleHeartbeat=$pdo->prepare('UPDATE baloot_room_players SET last_seen_at=UTC_TIMESTAMP(6)-INTERVAL 10 MINUTE WHERE guest_id=?');
$staleHeartbeat->execute([$staleOwner]);
verify($store->expireStaleLobbies()===1,'abandoned lobby expires after five minutes without active heartbeat');
verify(($store->read($staleRoom['code'])['status']??'')==='closed','expired lobby is no longer joinable');
try{$store->join($staleRoom['code'],str_repeat('8',64),'Late Guest');throw new RuntimeException('expired lobby accepted a new player');}
catch(RuntimeException $e){verify(str_contains($e->getMessage(),'صلاحية الغرفة'),'expired lobby returns a clear rejection');}
$quickAfterExpiry=$store->quickJoin(str_repeat('7',64),'Fresh Quick Guest',true);
verify($quickAfterExpiry['code']!==$staleRoom['code'],'quick join never selects an expired lobby');
$offline=$pdo->prepare('UPDATE baloot_room_players SET last_seen_at = UTC_TIMESTAMP(6) - INTERVAL 1 MINUTE WHERE guest_id IN (?, ?)');
$offline->execute([$guest2,$guest3]);
$presence=$store->read($code);
verify(empty($presence['state']['players'][1]['connected']) && empty($presence['state']['players'][2]['connected']),'stale player heartbeat marks disconnected seats offline');
verify($store->touchPlayer($code,$guest2),'heartbeat updates the returning player');
$presence=$store->read($code);
verify(!empty($presence['state']['players'][1]['connected']),'fresh heartbeat marks the returning player online');
$version=(int)$presence['version'];
$actionId='22222222-2222-4222-8222-222222222222';
$first=$store->mutate($code,$owner,$actionId,'test_change',function(array &$state,int $seat):array{$state['testMarker']='once';return ['value'=>42];},$version);
$duplicate=$store->mutate($code,$owner,$actionId,'test_change',function(array &$state,int $seat):array{throw new RuntimeException('duplicate action was executed twice');});
verify($first===$duplicate && $duplicate['value']===42,'action idempotency');
$afterAction=$store->read($code);
verify(($afterAction['state']['testMarker']??'')==='once' && $afterAction['version']===$version+1,'single version increment');
verify($store->allowRate('test',str_repeat('c',64),2,60),'rate limit first hit');
verify($store->allowRate('test',str_repeat('c',64),2,60),'rate limit second hit');
verify(!$store->allowRate('test',str_repeat('c',64),2,60),'rate limit blocks excess hit');
$startId='33333333-3333-4333-8333-333333333333';
$store->mutate($code,$owner,$startId,'start',function(array &$state,int $seat):array{Engine::start($state,$seat);return ['ok'=>true];});
$started=$store->read($code);
verify(($started['state']['game']['phase']??'')==='auction1','game state persisted in MySQL');
$expectedGuests=[$owner,$guest2,$guest3,$guest];
$privateHands=[];
foreach($expectedGuests as $expectedGuest){
    $seat=null;
    foreach($started['state']['players'] as $index=>$player){
        if(is_array($player)&&hash_equals((string)($player['guestId']??''),$expectedGuest)){$seat=(int)$index;break;}
    }
    verify($seat!==null,'reconnected player retains a seat by guest identity');
    $snapshot=Engine::snapshot($started['state'],$seat);
    verify($snapshot['mySeat']===$seat && count($snapshot['hand'])===5,'reconnected player receives their own persisted hand');
    verify(!array_key_exists('hands',$snapshot),'snapshot never exposes every player hand');
    $privateHands[$seat]=array_column($snapshot['hand'],'id');
}
for($a=0;$a<4;$a++)for($b=$a+1;$b<4;$b++)verify(!array_intersect($privateHands[$a],$privateHands[$b]),'private player hands do not overlap');
$deadlineId='44444444-4444-4444-8444-444444444444';
$store->mutate($code,$owner,$deadlineId,'test_deadline',function(array &$state,int $seat):array{$state['game']['turn']=0;$state['turnDeadlineAt']=time()-1;return ['ok'=>true];});
verify($store->advanceRoomBots($code),'normal room polling advances an expired human turn');
$timed=$store->read($code);
verify(($timed['state']['timeoutSeat']??-1)===0,'expired human turn is prompted');
$graceId='55555555-5555-4555-8555-555555555555';
$store->mutate($code,$owner,$graceId,'test_grace',function(array &$state,int $seat):array{$state['timeoutGraceUntil']=time()-1;$state['turnDeadlineAt']=time()-1;return ['ok'=>true];});
$store->advanceRoomBots($code);
$recovered=$store->read($code);
verify(!empty($recovered['state']['players'][0]['botControl']),'bot takes over after timeout grace');
$redealId='66666666-6666-4666-8666-666666666666';
$store->mutate($code,$owner,$redealId,'test_redeal_recovery',function(array &$state,int $seat):array{$state['game']['phase']='redeal';$state['game']['dealer']=0;$state['game']['round']=4;return ['ok'=>true];});
verify($store->advanceRoomBots($code),'normal room polling recovers a room stuck in redeal');
$redealt=$store->read($code);
verify(($redealt['state']['game']['phase']??'')==='auction1' && ($redealt['state']['game']['round']??0)===5,'stuck redeal recovers into a fresh auction');
verify(($redealt['state']['game']['dealer']??-1)===Rules::next(0) && array_sum(array_map('count',$redealt['state']['game']['hands']??[]))===20,'recovered redeal rotates dealer and deals new hands');
echo "MySQL room store, idempotency, rate limit and cron recovery tests passed\n";
